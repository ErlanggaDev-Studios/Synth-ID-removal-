/* Service worker Synth-ID Removal — cache shell agar bisa dipakai offline. */
const CACHE = "synthid-shell-v2";
const ASSETS = [
  "./",
  "./styles.css",
  "./app.js",
  "./manifest.webmanifest",
  "./icons/icon.svg",
  "./icons/icon-192.png",
  "./icons/icon-512.png",
  "./icons/icon-maskable-512.png",
  "./icons/apple-touch-icon-180.png",
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(ASSETS))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === "navigate") {
    /* Shell dari cache dulu supaya buka aplikasi tetap instan dan tetap
       jalan saat offline; versi baru masuk lewat service worker berikutnya.
       Yang di-cache adalah "./" karena host statis me-redirect /index.html
       ke "/" dan respons hasil redirect tidak boleh dipakai sebagai dokumen. */
    event.respondWith(
      caches.match("./").then((hit) => hit || fetch(request)),
    );
    return;
  }

  event.respondWith(
    caches.match(request).then((hit) => {
      if (hit) return hit;
      return fetch(request).then((response) => {
        if (response.ok) {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put(request, copy));
        }
        return response;
      });
    }),
  );
});
